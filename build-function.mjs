// Bundles the serverless function (including the workspace @campus/shared source)
// into a single self-contained file. Vercel's runtime cannot execute the raw
// TypeScript that packages/shared points at via its "main" entry, and only
// function files are uploaded, so the Postgres migration SQL is embedded as a TS module.
import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const pkg = JSON.parse(readFileSync(new URL('./apps/server/package.json', import.meta.url)));
const external = Object.keys(pkg.dependencies).filter((d) => d !== '@campus/shared');

const migrationDir = 'apps/server/migrations-postgres';
const files = readdirSync(migrationDir)
  .filter((f) => /^\d{3}_.*\.sql$/.test(f))
  .sort();
const embedded = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(path.join(migrationDir, f), 'utf8'))},`).join('\n');

const generated = 'apps/server/src/infrastructure/db/migrations.generated.ts';
const stub = '// Generated by build-function.mjs for serverless bundles. Empty in normal builds.\nexport const EMBEDDED_MIGRATIONS: Record<string, string> = {};\n';
writeFileSync(generated, `// Generated by build-function.mjs. Do not edit.\nexport const EMBEDDED_MIGRATIONS: Record<string, string> = {\n${embedded}\n};\n`);

await build({
  entryPoints: ['serverless/entry.ts'],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
  outfile: 'api/index.js',
  external,
  logLevel: 'info',
}).finally(() => writeFileSync(generated, stub)); // the bundle has the SQL; keep the source tree clean
